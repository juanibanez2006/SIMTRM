import os
from contextlib import contextmanager
from pathlib import Path


class SyncBusy(RuntimeError):
    pass


@contextmanager
def sync_lock(database_path: Path, *, suffix: str = ".sync.lock"):
    """An OS lock releases automatically if a sync process exits unexpectedly."""
    path = database_path.resolve().with_suffix(suffix)
    with path.open("a+b") as handle:
        handle.seek(0, os.SEEK_END)
        if handle.tell() == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise SyncBusy("Ya hay una sincronización en curso") from exc
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == "nt":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
